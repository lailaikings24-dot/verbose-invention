/**
 * DTC knowledge base: what each code means, why it set, and how to fix it.
 *
 * Codes are grouped by system. Every entry carries ranked causes and an
 * ordered diagnostic path so the repair screen can walk a user through it.
 */
export type Severity = 'low' | 'medium' | 'high' | 'critical';
export type Driveable = 'yes' | 'caution' | 'no';
export type Difficulty = 1 | 2 | 3;

export interface DtcInfo {
  code: string;
  title: string;
  system: string;
  severity: Severity;
  driveable: Driveable;
  /** One-line plain-language explanation. */
  summary: string;
  /** Ranked by likelihood, most common first. */
  causes: string[];
  symptoms: string[];
  /** Ordered diagnostic/repair steps. */
  steps: string[];
  parts: string[];
  cost: string;
  difficulty: Difficulty;
  /** Mode 01 PIDs worth watching while diagnosing. */
  watch: number[];
  related: string[];
  generic: boolean;
}

